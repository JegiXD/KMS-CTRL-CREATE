"""Prepare the reviewed additions without changing or deleting source photographs."""
import json
from hashlib import sha256
from pathlib import Path
from PIL import Image, ImageOps
ROOT=Path(__file__).resolve().parents[1]
archive=json.loads((ROOT/'KMS-Foto-Paket/docs/fotografije.json').read_text())
byfile={r['file']:r for r in archive}
records=[]
def prepare(key,original,folder,name,alt,credit,source,source_url,limit,kind='photo'):
 path=ROOT/original
 with Image.open(path) as opened:
  photo=ImageOps.exif_transpose(opened).convert('RGB');photo.thumbnail((limit,limit),Image.Resampling.LANCZOS)
  target=ROOT/'public/assets'/folder;target.mkdir(parents=True,exist_ok=True)
  photo.save(target/(name+'.jpg'),quality=87,optimize=True,progressive=True)
  photo.save(target/(name+'.webp'),quality=82,method=6)
  data=dict(src=f'/assets/{folder}/{name}.jpg',webpSrc=f'/assets/{folder}/{name}.webp',alt=alt,credit=credit,sourcePage=source,width=photo.width,height=photo.height,kind=kind)
 records.append(dict(key=key,original=original,originalSha256=sha256(path.read_bytes()).hexdigest(),jpegBytes=(target/(name+'.jpg')).stat().st_size,webpBytes=(target/(name+'.webp')).stat().st_size,sourceUrl=source_url,permission='KMŠ permission reported by user, 2026-11-04',**data))
 return data
photos={}
for key,file,folder,name,alt,credit in [
 ('cantusStage','events/kms-cantus-012.jpg','community','cantus-stage','Voditelja in udeleženci Cantusa v dvorani','Dostop.si'),
 ('cantusTogether','events/kms-cantus-014.jpg','community','cantus-together','Udeleženci in ekipa Cantusa ob mizi na odru','Dostop.si'),
 ('oderAudience','events/kms-kms-oder-007.jpg','gallery','oder-audience','Občinstvo pred nastopajočimi na KMŠ ODRU','Jure Bauman'),
 ('ftrgatevCrowd','events/kms-ftrgatev-003.jpg','gallery','ftrgatev-crowd','Občinstvo in osvetljen oder na Ftrgatvi','Andraž Kramberger')]:
 r=byfile[file];photos[key]=prepare(key,'KMS-Foto-Paket/assets/'+file,folder,name,alt,credit,r['source_page'],r['url'],1280)
people={}
for key,file in [('enej-polanec','Enej01-2-300x300.jpg'),('eva-polic','Eva02-300x300.jpg'),('zala-gluk','zala-2-300x300.jpg')]:
 people[key]=prepare(key,f'KMS-Foto-Paket/assets/verified-team/{key}.jpg','team',key,'Portret: '+{'enej-polanec':'Enej Polanec','eva-polic':'Eva Polič','zala-gluk':'Zala Gluk'}[key],'Vir: KMŠ','https://www.klub-kms.si/o-nas/','https://www.klub-kms.si/wp-content/uploads/2025/12/'+file,300,'portrait')
people['urban-kavkler']=prepare('urban-kavkler','KMS-Foto-Paket/assets/team/kms-ekipa-001.jpg','team','urban-kavkler-profile','Uradna profilna ilustracija Urbana Kavklerja; ni osebni portret','Vir: KMŠ','https://www.klub-kms.si/o-nas/','https://www.klub-kms.si/wp-content/uploads/2026/10/Rango_crop.jpg',320,'illustration')
(ROOT/'docs/PHOTO_REBALANCE_ASSETS.json').write_text(json.dumps(records,ensure_ascii=False,indent=2)+'\n')
(ROOT/'src/data/kmsPhotoAdditions.ts').write_text('// Verified additions. Generated by scripts/prepare-photo-review.py; provenance in docs/PHOTO_REBALANCE_ASSETS.json.\nexport const atmospherePhotos = '+json.dumps(photos,ensure_ascii=False,indent=2)+' as const;\n\nexport const additionalPeopleImages = '+json.dumps(people,ensure_ascii=False,indent=2)+' as const;\n')
print('Prepared',len(records),'verified assets, preserving all originals.')
